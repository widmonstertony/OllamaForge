import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {buildHybridConfiguration, createMetalCatalog, hybridEndpoint, metalAlias,installHybridConfiguration} from './codex-hybrid-config.mjs';
const cloudModels = [{slug:'gpt-current',default_reasoning_level:'high',visibility:'list'}];
const original = 'model = "gpt-current"\nmodel_reasoning_effort = "xhigh"\n\n[features]\nbrowser_use = true\n[mcp_servers.example]\nurl = "https://example.invalid"\n';
const cloud = buildHybridConfiguration(original, {cloudModels});
assert.match(cloud.configText, /model = "gpt-current"/);
assert.match(cloud.configText, /model_reasoning_effort = "xhigh"/);
assert.match(cloud.configText, /requires_openai_auth = true/);
assert.match(cloud.configText, /browser_use = true/);
assert.doesNotMatch(cloud.configText, /model_catalog_json/);
assert.equal(buildHybridConfiguration(cloud.configText,{cloudModels}).configText,cloud.configText);
const local = buildHybridConfiguration(cloud.configText,{cloudModels,preference:'local'});
assert.equal(local.model,metalAlias);
assert.match(local.configText,/model_provider = "openai"/);
assert.match(local.configText,/model_reasoning_effort = "none"/);
const updated = local.configText.replace('browser_use = true','browser_use = false');
const back = buildHybridConfiguration(updated,{cloudModels:[...cloudModels,{slug:'gpt-new',visibility:'list'}],preference:'cloud',recentSelection:{model:'gpt-new',reasoningEffort:'ultra'}});
assert.equal(back.model,'gpt-new');
assert.match(back.configText,/browser_use = false/);
assert.match(back.configText,/model_reasoning_effort = "ultra"/);
assert.match(back.configText,new RegExp(hybridEndpoint.replaceAll('.','\\.')));
const legacy='model = "'+metalAlias+'"\nmodel_provider = "local_qwen"\nmodel_context_window = 8192\nmodel_catalog_json = "/stale/catalog.json"\ndeveloper_instructions = "Local macOS runtime. Use native macOS/POSIX shell commands and paths."\ntool_output_token_limit = 1200\n[model_providers.local_qwen]\nbase_url = "http://127.0.0.1:11435/v1"\n';
const migrated=buildHybridConfiguration(legacy,{cloudModels,preference:'cloud'});
assert.doesNotMatch(migrated.configText,/model_catalog_json|model_context_window|developer_instructions|tool_output_token_limit/);
assert.equal(migrated.model,'gpt-current');
const custom=buildHybridConfiguration(original.replace('\n\n[features]','\ndeveloper_instructions = "Use Chinese"\n\n[features]'),{cloudModels});
assert.match(custom.configText,/developer_instructions = "Use Chinese"/);
assert.throws(()=>buildHybridConfiguration(original,{endpoint:'https://example.invalid'}),/local/);
const catalog=createMetalCatalog(JSON.parse(fs.readFileSync(new URL('./local-qwen-catalog.json',import.meta.url))));
assert.equal(catalog.models[0].slug,metalAlias);
assert.equal(catalog.models[0].context_window,8192);
assert.ok(catalog.models[0].priority > 100, 'Local metadata must not replace the native recommended cloud default.');
assert.deepEqual(catalog.models[0].supported_reasoning_levels.map(x=>x.effort),['none']);
const temporary=fs.mkdtempSync(path.join(os.tmpdir(),'forge-config-'));
try {
  const configPath=path.join(temporary,'config.toml');fs.writeFileSync(configPath,original);
  const installed=installHybridConfiguration({configPath,stateDir:temporary,sourceCatalogPath:new URL('./local-qwen-catalog.json',import.meta.url),localCatalogPath:path.join(temporary,'local.json'),cloudCachePath:path.join(temporary,'missing-cache.json'),preference:'cloud'});
  assert.equal(installed.model,'gpt-current');
  assert.ok(fs.readdirSync(temporary).some(name=>name.startsWith('config.pre-hybrid-')));
}finally{fs.rmSync(temporary,{recursive:true,force:true});}
console.log('PASS: persistent hybrid config, latest cloud selection and legacy migration.');
